TASK='''Extract metadata for THIS document from the supplied excerpts. Return one JSON
object with these exact keys:
{
 "publisher": null,
 "publication_date": null,
 "information_cutoffs": [],
 "reporting_periods": [],
 "reference_numbers": [],
 "keywords": [],
 "uncertainties": []
}
publisher, when supported, is {"value":"issuing organisation","evidence":[...]};
publication_date is {"value":"YYYY or YYYY-MM or YYYY-MM-DD","precision":"year|month|day","evidence":[...]}.
information_cutoffs items are {"value":"date as stated/normalized","scope":"what this date applies to","evidence":[...]}.
reporting_periods items are {"start":"date or null","end":"date or null","scope":"what is covered","evidence":[...]}.
reference_numbers items are {"type":"report_number|DOI|ISBN|other","value":"exact identifier","evidence":[...]}.
Each evidence item is {"excerpt_id":"E1","quote":"verbatim substring of that excerpt"}.
keywords are up to 8 concise suggested topic strings, labelled generated by this schema.
uncertainties are short strings explaining ambiguity or missing evidence.
Use JSON null (not the string 'unknown') and empty arrays for unsupported fields.
Keep multiple information dates with their scopes. Publication date is not the newest
date mentioned. Do not treat a cited work's publisher/date/number as this document's.
Do not use a filename, capture date or filesystem timestamp as proof of publication.
Do not expand an acronym from prior knowledge: retain its wording unless the supplied
text explicitly establishes the full name. Do not merge merely related keywords.
References and endnotes can describe other works; inspect the role of each statement.
A closing imprint about this document is valid evidence even on the final page.
Unknown is preferable to guessing. Do not invent unseen pages or evidence quotes.
Return JSON only after any model thinking. Do not wrap it in Markdown.
'''


def read_ids(path):
    ids=[]
    for number,line in enumerate(Path(path).read_text('utf-8-sig').splitlines(),1):
        value=line.split('#',1)[0].strip()
        if not value:continue
        if not re.fullmatch(r'[1-9][0-9]*',value):raise ValueError(f'Invalid source ID on line {number}')
        ident=int(value)
        if ident>2**63-1:raise ValueError(f'Source ID exceeds SQLite integer range on line {number}')
        ids.append(ident)
    if not ids or len(set(ids))!=len(ids):raise ValueError('IDs file must contain one or more unique positive sources.id values')
    return ids


def read_sources(database,ids):
    """Short read-only snapshot, no Library constructor, schema maintenance or writes."""
    from local_search.sqlite_paths import connect_readonly,network_path
    if network_path(Path(database).resolve()):raise ValueError('The authoritative search library must be local; copy a supported completed export to local storage first')
    db=connect_readonly(database,timeout=30)
    db.row_factory=sqlite3.Row
    try:
        db.execute('PRAGMA query_only=ON');db.execute('BEGIN')
        rows=[]
        for ident in ids:
            row=db.execute('''SELECT s.id AS source_id,s.doc_id,s.title,s.locator,s.collection,
                       s.status,s.added_at,s.modified_at,s.published_at,s.detail,d.text_hash,
                       length(d.text) AS total_chars
                       FROM sources s LEFT JOIN documents d ON d.id=s.doc_id WHERE s.id=?''',(ident,)).fetchone()
            if row is None:raise ValueError(f'Source ID {ident} does not exist; selection was not substituted')
            source=dict(row)
            if source['status']!='indexed' or source['doc_id'] is None:raise ValueError(f'Source ID {ident} has no indexed document ({source["status"]})')
            rows.append(source)
        # Preselect bounded front/back text. This avoids loading an enormous document.
        for source in rows:
            source['front']=db.execute('SELECT substr(text,1,200000) FROM documents WHERE id=?',(source['doc_id'],)).fetchone()[0]
            source['back']=db.execute('SELECT substr(text,max(1,length(text)-199999),200000) FROM documents WHERE id=?',(source['doc_id'],)).fetchone()[0]
            source['page_ranges']=[dict(r) for r in db.execute('SELECT page,min(start_char) AS start_char,max(end_char) AS end_char FROM locations WHERE doc_id=? GROUP BY page ORDER BY start_char',(source['doc_id'],))]
        return rows
    finally:db.close()


def excerpts_for(source,count):
    count=min(count,source['total_chars'],200000)
    if count==source['total_chars']:
        pieces=[(0,source['front'][:count])]
    else:
        head=(count*3)//4;tail=count-head
        pieces=[(0,source['front'][:head]),(source['total_chars']-tail,source['back'][-tail:] if tail else '')]
    excerpts=[]
    for start,text in pieces:
        if not text:continue
        pages=[r['page'] for r in source['page_ranges'] if r['page'] is not None and r['start_char']<start+len(text) and r['end_char']>start]
        excerpts.append({'excerpt_id':'E'+str(len(excerpts)+1),'start_char':start,'end_char':start+len(text),'pages':pages,'text':text})
    return excerpts


def prepare(source,model,system,max_input_tokens,max_chars):
    def messages(count):
        excerpts=excerpts_for(source,count)
        payload={'source_id':source['source_id'],'title_for_orientation_only':source['title'],
                 'total_indexed_chars':source['total_chars'],'evaluated_chars':sum(len(e['text']) for e in excerpts),
                 'excerpts':excerpts}
        return [{'role':'system','content':system},{'role':'user','content':TASK+'\n\n'+json.dumps(payload,ensure_ascii=False)}],excerpts
    ceiling=min(max_input_tokens,model.context-model.output)
    low=0;high=min(max_chars,source['total_chars'],200000)
    if model.count(messages(0)[0])>ceiling:raise ValueError('Prompt/schema alone exceeds input budget')
    while low<high:
        middle=(low+high+1)//2
        if model.count(messages(middle)[0])<=ceiling:low=middle
        else:high=middle-1
    prompt,excerpts=messages(low)
    if not excerpts:raise ValueError('No document text fits the input budget')
    return prompt,excerpts,model.count(prompt)


def parse_metadata(raw,excerpts):
    text=raw.rsplit('</think>',1)[-1].strip()
    if text.startswith('```'):text=re.sub(r'^```(?:json)?\s*|\s*```$','',text).strip()
    value=json.loads(text)
    required={'publisher','publication_date','information_cutoffs','reporting_periods','reference_numbers','keywords','uncertainties'}
    if not isinstance(value,dict) or set(value)!=required:raise ValueError('Expected exactly the documented metadata keys')
    available={e['excerpt_id']:e['text'] for e in excerpts};issues=[]
    def factual(item,field):
        if not isinstance(item,dict) or not isinstance(item.get('evidence'),list) or not item['evidence']:
            issues.append(field+': missing evidence');return
        for evidence in item['evidence']:
            if not isinstance(evidence,dict):issues.append(field+': invalid evidence');continue
            quote=evidence.get('quote');ident=evidence.get('excerpt_id')
            if not isinstance(quote,str) or not quote.strip() or quote not in available.get(ident,''):
                issues.append(field+': evidence quote not present in specified excerpt')
    for field in ('publisher','publication_date'):
        if value[field] is not None:
            factual(value[field],field)
            if not isinstance(value[field],dict) or not isinstance(value[field].get('value'),str) or not value[field]['value'].strip():
                issues.append(field+': value must be nonempty text')
    date=value['publication_date']
    if isinstance(date,dict):
        patterns={'year':r'[0-9]{4}','month':r'[0-9]{4}-[0-9]{2}','day':r'[0-9]{4}-[0-9]{2}-[0-9]{2}'}
        precision=date.get('precision')
        if precision not in patterns or not re.fullmatch(patterns[precision],str(date.get('value',''))):issues.append('publication_date: value/precision mismatch')
        else:
            try:datetime.fromisoformat(date['value']+{'year':'-01-01','month':'-01','day':''}[precision])
            except ValueError:issues.append('publication_date: invalid calendar date')
    for field in ('information_cutoffs','reporting_periods','reference_numbers'):
        if not isinstance(value[field],list):raise ValueError(field+' must be a list')
        for item in value[field]:
            factual(item,field)
            if not isinstance(item,dict):continue
            if field in ('information_cutoffs','reference_numbers') and (not isinstance(item.get('value'),str) or not item['value'].strip()):issues.append(field+': missing value')
            if field in ('information_cutoffs','reporting_periods') and (not isinstance(item.get('scope'),str) or not item['scope'].strip()):issues.append(field+': missing scope')
            if field=='reporting_periods':
                if not {'start','end'}<=set(item) or all(item.get(k) is None for k in ('start','end')):issues.append(field+': missing period endpoints')
                if any(item.get(k) is not None and not isinstance(item[k],str) for k in ('start','end')):issues.append(field+': endpoints must be text or null')
            if field=='reference_numbers' and item.get('type') not in ('report_number','DOI','ISBN','other'):issues.append(field+': unsupported identifier type')
    if not isinstance(value['keywords'],list) or len(value['keywords'])>8 or any(not isinstance(k,str) for k in value['keywords']):raise ValueError('keywords must contain at most 8 strings')
    if not isinstance(value['uncertainties'],list) or any(not isinstance(k,str) for k in value['uncertainties']):raise ValueError('uncertainties must be strings')
    return value,issues


def source_url(locator):
    parts=urlsplit(locator)
    if parts.scheme.lower() in ('http','https') and parts.netloc:return locator
    path=Path(locator)
    return path.as_uri() if path.is_absolute() and path.suffix.lower()=='.pdf' else None


def write_report(directory,run):
    directory=Path(directory);directory.mkdir(parents=True,exist_ok=True)
    (directory/'results.json').write_text(json.dumps(run,ensure_ascii=False,indent=2),'utf-8')
    esc=lambda value:html.escape(str(value),quote=True)
    parts=['<!doctype html><meta charset="utf-8"><title>Metadata extraction review</title>',
           '<style>body{max-width:1100px;margin:32px auto;font:16px system-ui}pre{white-space:pre-wrap;overflow-wrap:anywhere;background:#f3f3f3;padding:16px}article{border-top:2px solid #aaa;margin-top:32px}a{color:#145da0}</style>',
           '<h1>Metadata extraction review</h1><p>Source IDs: '+esc(run['source_ids'])+'</p>',
           '<p>Read-only trial. Fields are suggestions, not saved to the library. Evidence matching checks literal text, not whether a field is semantically correct.</p>',
           '<details><summary>Exact extraction prompts</summary><pre>'+esc(run['system_prompt'])+'\n\n'+esc(TASK)+'</pre></details>']
    for result in run['results']:
        source=result['source'];ident=source['source_id'];filename=Path(source['locator']).name
        parts+=['<article><h2>'+esc(str(ident)+' — '+source['title'])+'</h2><p>Filename: '+esc(filename)+'<br>Path / URL: '+esc(source['locator'])+'</p>']
        link=source_url(source['locator'])
        if link:parts+=['<p><a href="'+esc(link)+'">Open original file / source</a></p>']
        parts+=['<p>Status: '+esc(result['status'])+'; evaluated '+esc(result.get('evaluated_chars',0))+' / '+esc(source['total_chars'])+' indexed characters. '+('FULL indexed text.' if result.get('full_indexed_text') else 'PARTIAL text; middle content may be omitted.')+'</p>',
                '<p>Document hash: '+esc(source['text_hash'])+'</p><pre>'+esc(json.dumps(result.get('metadata',{'error':result.get('error')}),ensure_ascii=False,indent=2))+'</pre>',
                '<p>Validation issues: '+esc(result.get('validation_issues',[]))+'</p>']
        for excerpt in result.get('excerpts',[]):
            name=f'source-{ident}-{excerpt["excerpt_id"]}.txt';(directory/name).write_text(excerpt['text'],'utf-8')
            parts+=['<details><summary>Exact evaluated text '+esc(excerpt['excerpt_id'])+' — chars '+esc(excerpt['start_char'])+'–'+esc(excerpt['end_char'])+', pages '+esc(excerpt['pages'])+'</summary><p><a href="'+esc(name)+'">Open plain text</a></p><pre>'+esc(excerpt['text'])+'</pre></details>']
        parts+=['<details><summary>Raw model output / timings</summary><pre>'+esc(result.get('raw_output',''))+'\n'+esc(json.dumps(result.get('timings',{}),indent=2))+'</pre></details></article>']
    (directory/'report.html').write_text('\n'.join(parts),'utf-8')


def run_trial(sources,ids,model,system,directory,max_input_tokens,max_chars,model_info=None):
    run={'created_at':datetime.now(timezone.utc).isoformat(),'source_ids':ids,'system_prompt':system,
         'system_prompt_sha256':hashlib.sha256(system.encode('utf-8')).hexdigest(),'task_prompt':TASK,
         'context':model.context,'output_reserve':model.output,'max_input_tokens':max_input_tokens,'max_chars':max_chars,
         'keyword_origin':'generated suggestions','model':model_info,'results':[]}
    for source in sources:
        started=time.perf_counter();result={'source':{k:v for k,v in source.items() if k not in ('front','back','page_ranges')},'status':'error'}
        try:
            messages,excerpts,prompt_tokens=prepare(source,model,system,max_input_tokens,max_chars)
            result.update(excerpts=excerpts,evaluated_chars=sum(len(e['text']) for e in excerpts),prompt_tokens=prompt_tokens,
                          full_indexed_text=sum(len(e['text']) for e in excerpts)==source['total_chars'])
            response=model.complete(messages);raw=response['choices'][0]['text']
            result.update(raw_output=raw,timings=response.get('timings',{}),usage=response.get('usage',{}))
            if response['choices'][0].get('finish_reason')=='length':raise ValueError('Output reserve exhausted; increase reserve or disable thinking')
            metadata,issues=parse_metadata(raw,excerpts)
            result.update(metadata=metadata,validation_issues=issues,status='needs_review' if issues else 'extracted')
        except Exception as error:result['error']=str(error)
        result['total_seconds']=time.perf_counter()-started;run['results'].append(result)
        write_report(directory,run)
        print(f'Source {source["source_id"]}: {result["status"]} ({result["total_seconds"]:.1f}s)',flush=True)
    return run


def main():
    if sys.stdout is not None:sys.stdout.reconfigure(encoding='utf-8')
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config',type=Path,default=Path('local-search.json'))
    parser.add_argument('--ids-file',type=Path,default=Path(__file__).with_name('metadata-demo-ids.txt'))
    parser.add_argument('--prompts-file',type=Path)
    parser.add_argument('--output-dir',type=Path)
    parser.add_argument('--max-input-tokens',type=int,default=48000)
    parser.add_argument('--max-chars',type=int,default=120000)
    args=parser.parse_args()
    if args.max_input_tokens<1 or not 1<=args.max_chars<=200000:parser.error('Use a positive token budget and max-chars 1..200000')
    config=configuration(args.config);ids=read_ids(args.ids_file)
    system=load_prompt('metadata.system',args.prompts_file or config.get('prompts_file'))
    sources=read_sources(config['database'],ids)
    directory=args.output_dir or Path('data')/('metadata-demo-'+datetime.now().strftime('%Y%m%d-%H%M%S-%f'))
    if directory.exists() and any(directory.iterdir()):parser.error('Output directory must be new or empty')
    model=GGUF(**config['model'])
    info={'backend':'local GGUF','filename':Path(config['model']['path']).name,
          'thinking':config['model'].get('thinking',False),'gpu_layers':config['model'].get('gpu_layers',0),
          'ids_file':str(args.ids_file.resolve())}
    try:run=run_trial(sources,ids,model,system,directory,args.max_input_tokens,args.max_chars,info)
    finally:model.close()
    print('Review report: '+str((directory/'report.html').resolve()))
    if any(r['status']=='error' for r in run['results']):raise SystemExit(1)


if __name__=='__main__':
    try:main()
    except (ValueError,OSError,sqlite3.Error) as error:raise SystemExit(str(error))
